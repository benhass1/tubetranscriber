def _fetch_transcript_in_language(video_id: str) -> TranscriptResult:
    """Fetch only the caption track matching the video's original audio language."""
    try:
        return _fetch_timedtext_direct_result(video_id)
    except (RuntimeError, requests.RequestException):
        # The direct list is the fastest path. If it is blocked, use the
        # InnerTube catalog before handing control to the legacy stack.
        tracks, _translations = _discover_caption_catalog(video_id)
        original_track = _select_original_caption_track(tracks)
        session = _youtube_session()
        try:
            segments = _fetch_caption_track(session, original_track, _po_token_details(video_id))
        finally:
            session.close()
        return _result(segments, tracks, original_track, original_track, [])


def _fetch_transcript_result(video_id: str) -> TranscriptResult:
    """Use the original-language catalog first, retaining the complete fallback stack."""
    try:
        return _fetch_transcript_in_language(video_id)
    except (RuntimeError, requests.RequestException) as catalog_error:
        try:
            return _youtube_transcript_api_fetch_result(video_id)
        except Exception:
            pass
        try:
            return _fetch_innertube_api_key_result(video_id)
        except Exception:
            pass
        try:
            return _fetch_ytdlp_transcript_result(video_id)
        except Exception:
            pass
        try:
            segments = _fetch_transcript(video_id)
        except Exception:
            if isinstance(catalog_error, RuntimeError):
                raise catalog_error
            raise RuntimeError(f"Initial transcript extraction failed: {catalog_error}") from catalog_error
        selected = {"languageCode": "", "name": "Original language"}
        return _result(segments, [], selected, selected, [])


def _fetch_transcript(video_id: str) -> list[dict[str, Any]]:
    """Prefer direct timedtext, then InnerTube/page extraction, then the library."""
    prior_errors: list[Exception] = []
    for fetcher in (_fetch_timedtext_direct, _fetch_innertube_transcript, _fetch_direct_transcript, _fetch_ytdlp_transcript):
        try:
            return fetcher(video_id)
        except YouTubeRateLimitError as error:
            # The Worker and WARP may use different egress paths. Keep the
            # library fallback available before returning a final 429.
            prior_errors.append(error)
            continue
        except (RuntimeError, requests.RequestException) as error:
            prior_errors.append(error)

    try:
        return _youtube_transcript_api_fetch(video_id)
    except TranscriptsDisabled as error:
        raise NoCaptionsError("No public captions are available for this video.") from error
    except NoTranscriptFound as error:
        raise NoCaptionsError("No public captions are available for this video.") from error
    except VideoUnavailable as error:
        raise RuntimeError("The requested video is unavailable or private.") from error
    except RuntimeError as error:
        message = str(error)
        lowered = message.lower()
        prior_messages = " ".join(str(item).lower() for item in prior_errors)
        if any(token in lowered or token in prior_messages for token in ("429", "too many requests", "rate limit", "ratelimit")):
            raise YouTubeRateLimitError("YouTube is temporarily rate-limiting transcript requests.") from error
        if "unavailable or private" in prior_messages or "unavailable or private" in lowered:
            raise RuntimeError("The requested video is unavailable or private.") from error
        if any(isinstance(item, NoCaptionsError) for item in prior_errors) and not any(
            isinstance(item, CaptionPayloadError) for item in prior_errors
        ):
            raise NoCaptionsError("No public captions are available for this video.") from error
        if "no element found" in lowered or "empty" in lowered or "xml" in lowered:
            raise YouTubeRateLimitError(
                "YouTube is temporarily limiting transcript requests. Please wait a moment and try again."
            ) from error
        raise
    except Exception as error:
        error_message = str(error)
        lowered = error_message.lower()
        if any(token in lowered for token in ("429", "too many requests", "rate limit", "ratelimit")):
            raise YouTubeRateLimitError("YouTube is temporarily rate-limiting transcript requests.") from error
        if any(isinstance(item, NoCaptionsError) for item in prior_errors) and not any(
            isinstance(item, CaptionPayloadError) for item in prior_errors
        ):
            raise NoCaptionsError("No public captions are available for this video.") from error
        if "no element found" in lowered or "empty" in lowered or "xml" in lowered:
            raise YouTubeRateLimitError(
                "YouTube is temporarily limiting transcript requests. Please wait a moment and try again."
            ) from error
        raise RuntimeError(f"Transcript extraction failed: {error_message}") from error


def get_transcript(url_or_id: str) -> str:
    """Extract and format a transcript as plain text."""
    video_id = extract_video_id(url_or_id)
    transcript = _fetch_transcript_result(video_id)
    return TextFormatter().format_transcript(transcript["segments"])


def get_transcript_payload(url_or_id: str) -> dict[str, Any]:
    """Extract the original-language transcript and return its metadata."""
    video_id = extract_video_id(url_or_id)
    result = _fetch_transcript_result(video_id)
    transcript = result["segments"]
    plain_text = re.sub(r"\s+", " ", TextFormatter().format_transcript(transcript)).strip()
    segments = [
        {
            "text": re.sub(r"\s+", " ", str(item.get("text", ""))).strip(),
            "start": max(0, float(item.get("start", 0) or 0)),
            "duration": max(0, float(item.get("duration", 0) or 0)),
        }
        for item in transcript
    ]
    return {
        "segments": [item for item in segments if item["text"]],
        "plainText": plain_text,
        "originalLanguage": result.get("originalLanguage"),
    }


def main() -> None:
    raw_request = sys.stdin.read().strip()
